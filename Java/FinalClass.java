//
// Class Name(s) : Demo, Hello, FinalClass
// Input         : None
// Output        : Compilation error due to inheritance attempt
// Methods       : Fun(), Gun()
// Description   : Demonstrates restriction of inheritance using final class in Java.
// Author        : Samruddh Shivkumar Birajdar
//
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

final class Demo{
    public void Fun(){ System.out.println("Inside Demo Fun."); }

    public void Gun(){ System.out.println("Inside Demo Gun."); }
}

class Hello extends Demo{  // Error 
    public void Gun(){ System.out.println("Inside Hello Gun."); }
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
// Application : Attempts to inherit from a final class, causing error.
//
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

class FinalClass{
    public static void main(String[] args) {
        Hello Hobj = new Hello();
    }
}

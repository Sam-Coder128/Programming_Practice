// Class Name(s) : Demo, ThreadScenario1X
// Input         : None
// Output        : Prints main thread message and run method message
// Methods       : run(), start()
// Description   : Demonstrates creating a thread using Thread object with Runnable in Java.
// Author        : Samruddh Shivkumar Birajdar
//
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

class Demo extends Thread{
    public void run(){ System.out.println("Inside Run Method."); }
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
// Application : Shows execution of main thread and child thread using Thread object.
//
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

class ThreadScenario1X{
    public static void main(String[] args) {
        
        System.out.println("Main thread is running...");

        Demo dobj = new Demo();

        Thread tobj = new Thread(dobj);

        tobj.start();
    }
}

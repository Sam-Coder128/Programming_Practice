////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
// Class Name(s) : Demo, Hello, FinalMethod
// Input         : None
// Output        : Compilation error due to overriding final method
// Methods       : Fun(), Gun()
// Description   : Demonstrates restriction of method overriding using final keyword in Java.
// Author        : Samruddh Shivkumar Birajdar
//
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

class Demo{
    public void Fun(){ System.out.println("Inside Demo Fun."); }

    public final void Gun(){ System.out.println("Inside Demo Gun."); }
}

class Hello extends Demo{
    public void Gun(){ System.out.println("Inside Hello Gun."); }
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
// Application : Attempts to override a final method, causing error.
//
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

class FinalMethod{
    public static void main(String[] args) {
        Hello Hobj = new Hello();
    }
}
